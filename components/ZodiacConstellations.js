export function Constellation({ sign, className }) {
  const data = SIGNS[sign];
  if (!data) return null;
  const { points, edges } = data;

  return (
    <svg viewBox="0 0 100 100" className={className || 'deco-constellation'} aria-hidden="true">
      {edges.map(([a, b], i) => (
        <line
          key={i}
          x1={points[a][0]}
          y1={points[a][1]}
          x2={points[b][0]}
          y2={points[b][1]}
          className="constellation-line"
        />
      ))}
      {points.map(([x, y], i) => (
        <circle key={i} cx={x} cy={y} r={i === 0 ? 3 : 2} className="constellation-star" />
      ))}
    </svg>
  );
}
